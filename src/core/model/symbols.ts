/** 拍平后的全量，顺序 = 类目顺序 + 类目内顺序（面板就按这个铺） */
export const SYMBOLS: Sym[] = CATEGORIES.flatMap((cat) =>
  RAW[cat].map(([ch, name, keys]) => ({ ch, name, cat, keys: keys ?? '' })),
)

const norm = (s: string) => s.trim().toLowerCase()

/**
 * 搜符号。空查询返回全部。
 *
 * 顺序讲究：字符本身命中 > 名字命中 > 关键词命中 —— 用户输 `→` 时
 * 期望那条排第一，而不是被一堆关键词里带箭头的挤到后面。
 */
export function searchSymbols(list: Sym[], q: string): Sym[] {
  const t = norm(q)
  if (!t) return list

  const rank = (s: Sym): number => {
    if (s.ch === q.trim()) return 0
    if (norm(s.name) === t) return 1
    if (norm(s.name).includes(t)) return 2
    if (s.keys.toLowerCase().includes(t)) return 3
    if (s.cat.includes(t)) return 4
    return -1
  }

  return list
    .map((s) => ({ s, r: rank(s) }))
    .filter((x) => x.r >= 0)
    .sort((a, b) => a.r - b.r)
    .map((x) => x.s)
}

/** 最近用过：把 ch 插到最前，去掉重复，截断到 max */
export function withRecent(recent: string[], ch: string, max = 16): string[] {
  return [ch, ...recent.filter((c) => c !== ch)].slice(0, max)
}

/** 这个字符是不是"一个符号"（防止把整段文字塞进图标字段） */
export function isSymbol(s: string): boolean {
  const t = s.trim()
  if (!t) return false
  // 允许 1–2 个码位 + 变体选择符 / ZWJ 序列（👨‍💻 这种由多个码位组成）
  return [...t].length <= 8 && !/[\s\u4e00-\u9fa5A-Za-z0-9]/.test(t)
}
