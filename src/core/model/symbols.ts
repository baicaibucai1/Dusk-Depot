/*
 * 给用户用的符号目录 —— 和界面图标（lucide）不是一回事。
 *
 * ## 为什么是 emoji 字符，而不是一套 SVG
 *
 * 这一层的符号要能**插进正文**。正文是普通 markdown，得能在 VS Code、GitHub、
 * 手机上打开还成立 —— 所以能存下的只有**字符**，存图片就死了。
 * 于是：面板里放 emoji 字符，渲染交给系统字体（Segoe UI Emoji / Apple Color Emoji）。
 * 零依赖、零协议负担，包体一个字节不涨。
 *
 * ## 代价（写在这里免得以后有人以为是 bug）
 *
 * 同一个 emoji 在 Windows / macOS / 安卓上长得不完全一样，这是字体的事。
 * 我们不打包字体，所以不追求"处处像素一致"，只保证"语义一致"。
 *
 * ## 加符号的规矩
 *
 *   ① 一个字符只出现在一个类目里 —— 重复出现会让"最近使用"和搜索都变脏
 *   ② 名字用**用户会打的词**（"完成"而不是"对勾"），关键词补同义词
 *   ③ 别塞整本 Unicode。面板是给人翻的，一个类目超过 ~20 个就翻不动了
 */

